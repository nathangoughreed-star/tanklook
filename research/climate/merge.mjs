// Merges research/climate/batch-N.json into src/data/climatedata.ts (run: node research/climate/merge.mjs)
import fs from 'node:fs';
const AIR_IDS = new Set(['dartfrog', 'treefrog', 'crestedgecko', 'crestedharlequin', 'regaljumper', 'chacogoldenknee', 'firetoad', 'firenewt']);
const all = [];
for (let i = 1; i <= 11; i++) all.push(...JSON.parse(fs.readFileSync(`research/climate/batch-${i}.json`, 'utf8')));
const J = v => JSON.stringify(v);
const water = [], air = [];
for (const x of all) {
  const est = x.confidence === 'low' ? ', est: true' : '';
  const isAirOnly = AIR_IDS.has(x.id) && !x.airOk;
  if (!isAirOnly) water.push(`  ${x.id}: { ok: ${J(x.ok)}, tol: ${J(x.tol)}${est} },`);
  if (AIR_IDS.has(x.id)) {
    const c = x.airOk ?? x.ok, tol = x.airTol ?? x.tol;
    const f = [`c: ${J(c)}`, `tol: ${J(tol)}`];
    if (x.rh) f.push(`rh: ${J(x.rh)}`); if (x.rhTol) f.push(`rhTol: ${J(x.rhTol)}`);
    if (x.warm) f.push(`warm: ${J(x.warm)}`); if (x.night) f.push(`night: ${J(x.night)}`);
    air.push(`  ${x.id}: { ${f.join(', ')}${est} },`);
  }
}
fs.writeFileSync('src/data/climatedata.ts', `// GENERATED by research/climate/merge.mjs from research/climate/batch-*.json (2026-10-19). Do not edit by hand.
// Comfortable (ok) and tolerable (tol) ranges, deg C (water) / air; \`est\` marks low-confidence rows (thin sources, partly judgement).
type R = [number, number];
export const WATER: Record<string, { ok: R; tol: R; est?: true }> = {
${water.join('\n')}
};
export const AIRDATA: Record<string, { c: R; tol: R; rh?: R; rhTol?: R; warm?: R; night?: R; est?: true }> = {
${air.join('\n')}
};
`);
console.log(water.length, 'water,', air.length, 'air');
