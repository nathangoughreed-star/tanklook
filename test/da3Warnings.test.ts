// DA3 (2026-11-03): the group-size and sex-ratio lines scale with the shortfall and speak in likelihoods. Set DA3_AUDIT=1 to
// regenerate research/design/da3-group-warning-audit.md (every species' group line and sexed note, before / after).
import { describe, expect, it } from 'vitest';
import { GROUPS, bandMessage, groupTone } from '../src/data/groups';
import { notesOf } from '../src/ui/stockPlanLogic';
import { speciesLive } from '../src/ui/discovery/animalsLive';
import { TANK_MODELS } from '../src/data/tanks';

const withBands = Object.entries(GROUPS).filter(([, g]) => g.bands);

describe('DA3 calm group warnings', () => {
  it('a count one under bands.ok is never red unless the species marks harm below it', () => {
    for (const [id, g] of withBands) {
      const n = g.bands!.ok - 1;
      if (n < 1) continue;
      const tone = groupTone(g, n);
      if (tone === 'bad') expect(n <= 1 || (g.harmBelow !== undefined && n < g.harmBelow), `${id} at ${n}`).toBe(true);
    }
    expect(groupTone(GROUPS.cherryshrimp, 1)).toBe('warn');
    {
    }
  });
  it('red is only a lone animal of a 4+ shoaler or below harmBelow', () => {
    for (const [id, g] of withBands) for (let n = 1; n < g.bands!.ok; n++) {
      if (groupTone(g, n) === 'bad') expect(g.harmBelow !== undefined ? n < g.harmBelow : n === 1 && g.bands!.ok >= 4, `${id} ${n}`).toBe(true);
    }
  });
  it('chromis at 5 is amber and says it is a little under; a lone chromis is red', () => {
    expect(groupTone(GROUPS.chromis, 5)).toBe('warn');
    expect(bandMessage(GROUPS.chromis, 5)).toMatch(/^A little under/);
    expect(groupTone(GROUPS.chromis, 1)).toBe('bad');
    expect(groupTone(GROUPS.chromis, 6)).toBe('note');
  });
  it('the chromis card at 5 has no red group line', () => {
    const tank = TANK_MODELS.find(m => !m.terrarium && m.ratedGal >= 90)!;
    const sl = speciesLive([{ species: 'chromis', n: 5 }], tank)[0];
    expect(sl.lines.find(l => /^Group size/.test(l.text))?.tone).toBe('warn');
  });
  it('breeding-only ratios are a grey tip, never a warning, and never "short on females"', () => {
    const only = Object.entries(GROUPS).filter(([, g]) => g.sexed?.breedingOnly);
    expect(only.map(([id]) => id)).toContain('cherryshrimp');
    for (const [id] of only) for (const [m, f] of [[1, 1], [2, 1], [3, 1], [5, 0], [0, 6]]) {
      const nt = notesOf({ id, n: m, f });
      expect(nt.ratio, id).toMatch(/^Tip: /);
      expect(nt.ratio).not.toMatch(/short on females|Your mix/);
    }
    const tank = TANK_MODELS.find(m => !m.terrarium && m.ratedGal >= 20)!;
    const l = speciesLive([{ species: 'cherryshrimp', n: 3, f: 2 }], tank)[0].lines.find(x => /^Tip:/.test(x.text));
    expect(l?.tone).toBe('note');
  });
  it('harm cases (fighting males) still warn about the mix', () => {
    expect(notesOf({ id: 'peacock', n: 3, f: 1 }).ratio).toMatch(/short on females/);
  });
  it('no group line states a flat cause without a hedge', () => {
    for (const [id, g] of withBands) {
      const m = g.msg?.avoid; if (!m) continue;
      expect(m, id).not.toMatch(/\b(will kill|kills the rest|bullies the rest|are stressed)\b/);
    }
  });
});

if ((globalThis as any).process?.env.DA3_AUDIT) it('writes the audit', async () => {
  // @ts-expect-error node only (no node types in this project)
  const { execSync } = await import('node:child_process');
  // @ts-expect-error node only (no node types in this project)
  const { readFileSync, writeFileSync } = await import('node:fs');
  const old = execSync('git show origin/main:src/data/groups.ts', { encoding: 'utf8', maxBuffer: 1 << 24 });
  const oldAvoid: Record<string, string> = {}, oldSex: Record<string, string> = {};
  for (const line of old.split('\n')) {
    const id = /^ {2}(\w+): \{/.exec(line)?.[1]; if (!id) continue;
    const a = /avoid: ['"]([^'"]*)['"]/.exec(line)?.[1]; if (a) oldAvoid[id] = a;
    const sx = /sexed: \{[^}]*note: ['"]([^'"]*)['"]/.exec(line)?.[1]; if (sx) oldSex[id] = sx;
  }
  const src = readFileSync('research/groups-sources.md', 'utf8').split('\n');
  const source = (id: string) => { const l = src.find((x: string) => x.startsWith(`- **${id}**`)); if (!l) return 'none'; const u = /https?:\/\/[^\s)]+/.exec(l)?.[0]?.replace(/[.,;:]+$/, ''); return `${u ?? 'see file'}${/\(est\)/.test(l) ? ' (est)' : ''}`; };
  const out = ['# DA3 group-warning audit (2026-11-03)', '', 'Tone before: the whole avoid band was red (bad). After: red only for a lone animal of a 4+ shoaler or below the species\' own `harmBelow`; any other shortfall amber (warn), with "A little under: N or more is the usual group" when one short (or 80 %+). Generated by `DA3_AUDIT=1 npx vitest run test/da3Warnings.test.ts`.', '',
    '## Group-size lines (the "avoid" band: fewer than bands.ok)', '', '| species | ok | tone one under | tone at 1 | claim before | claim after | source |', '|---|---|---|---|---|---|---|'];
  const unsourced: string[] = [];
  for (const [id, g] of withBands) {
    const ok = g.bands!.ok; if (ok <= 1) continue;
    const s = source(id); if (s === 'none' || /\(est\)/.test(s)) unsourced.push(id);
    const after = g.msg?.avoid ?? `(generated) ${bandMessage(g, 1)}`;
    out.push(`| ${id} | ${ok} | ${groupTone(g, ok - 1)} | ${groupTone(g, 1)} | ${oldAvoid[id] ?? '(generated)'} | ${after} | ${s} |`);
  }
  out.push('', '## Sexed notes', '', '| species | ratio | breeding only | note before | note after | tone |', '|---|---|---|---|---|---|');
  for (const [id, g] of Object.entries(GROUPS)) if (g.sexed) out.push(`| ${id} | ${g.sexed.ratio.join(':')} | ${g.sexed.breedingOnly ? 'yes' : 'no'} | ${oldSex[id] ?? ''} | ${g.sexed.note ?? ''} | ${g.sexed.breedingOnly ? 'grey tip' : 'warning when the mix is short on females (harassment / fighting)'} |`);
  out.push('', '## Not sourced to a published page (estimates or no row in research/groups-sources.md)', '', unsourced.join(', '));
  writeFileSync('research/design/da3-group-warning-audit.md', out.join('\n') + '\n');
});
